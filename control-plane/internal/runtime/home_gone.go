// home_gone.go — the runtime's answer to "is this member's home gone?", asked before the CP
// deletes the credential-store key sealed for it (home_dek). A key dropped while any of the
// home survives makes what survives unreadable, so the question has three answers and the
// zero value is the cautious one.
package runtime

import (
	"context"
	"errors"
	"os"
	"path/filepath"
)

// HomeVerdict is what an adapter can prove about a member's home.
type HomeVerdict int

const (
	// HomeUnknown: the adapter cannot tell. The zero value, so a forgotten branch keeps the key.
	HomeUnknown HomeVerdict = iota
	// HomeGone: the adapter looked, or ran the removal itself, and no byte of the home is left.
	HomeGone
	// HomePresent: some of the home is still there.
	HomePresent
)

func (v HomeVerdict) String() string {
	switch v {
	case HomeGone:
		return "gone"
	case HomePresent:
		return "present"
	}
	return "unknown"
}

// homeProver is a separate port from Runtime, like runtimeDestroyer: a Runtime that does not
// implement it is HomeUnknown.
//
// "Destroy returned no leftovers" is not a proof and no adapter may answer HomeGone from it:
// ecs without the home task removes only the access points and a retry then reports nothing
// left. An adapter answers HomeGone only from what it observed about the home itself, and
// anything it could not observe is HomeUnknown, never HomeGone. The reason is for the log.
type homeProver interface {
	ProveHomeGone(ctx context.Context) (HomeVerdict, string)
}

// ProveHomeGone asks rt's adapter. An adapter without the method, and a context that is
// already done, answer HomeUnknown.
func ProveHomeGone(ctx context.Context, rt Runtime) (HomeVerdict, string) {
	p, ok := rt.(homeProver)
	if !ok {
		return HomeUnknown, "the runtime cannot prove a home gone"
	}
	if ctx.Err() != nil {
		return HomeUnknown, ctx.Err().Error()
	}
	return p.ProveHomeGone(ctx)
}

// Every adapter answers (the same list as the destroyer's, for the same reason).
var (
	_ homeProver = (*dockerRuntime)(nil)
	_ homeProver = (*nativeRuntime)(nil)
	_ homeProver = (*ecsRuntime)(nil)
	_ homeProver = (*ecsEC2Runtime)(nil)
	_ homeProver = (*kubeRuntime)(nil)
)

// proveLocalHomeGone is docker's and native's proof: their whole home is <dataDir> on the
// CP's own host. Absence counts only while the data root above it is there, so a CP started
// with the wrong WS_DATA (or without its volume) does not read an unmounted tree as "gone".
func proveLocalHomeGone(dataDir string) (HomeVerdict, string) {
	if dataDir == "" || !filepath.IsAbs(dataDir) {
		return HomeUnknown, "no data directory is known for this home"
	}
	root, err := os.Stat(filepath.Dir(dataDir))
	if err != nil || !root.IsDir() {
		return HomeUnknown, "the data root above the home is not readable"
	}
	_, err = os.Lstat(dataDir)
	switch {
	case err == nil:
		return HomePresent, "the data directory exists"
	case errors.Is(err, os.ErrNotExist):
		return HomeGone, "the data directory is absent under a present data root"
	}
	return HomeUnknown, "the data directory cannot be read: " + err.Error()
}

func (d *dockerRuntime) ProveHomeGone(context.Context) (HomeVerdict, string) {
	return proveLocalHomeGone(d.dataDir)
}

func (n *nativeRuntime) ProveHomeGone(context.Context) (HomeVerdict, string) {
	return proveLocalHomeGone(n.dataDir)
}

// ecsRuntime.homeDestroyed records, on the runtime value that ran it, that the EFS home task
// exited 0 for a destroy: that task removes /home/<id>, /claude-config/<id> and /home-keep/<id>
// and fails on anything it could not remove, so its exit is the one observation of the EFS
// side. Nothing is read from the file system afterwards (the CP cannot mount it), so a fresh
// runtime value has no proof. A plain bool: Destroy and the proof run one after the other on
// the value the lifecycle lease holds, and the struct is copied by value elsewhere.
func (e *ecsRuntime) ProveHomeGone(context.Context) (HomeVerdict, string) {
	if e.homeDestroyed {
		return HomeGone, "the destroy task removed the EFS home"
	}
	return HomeUnknown, "the CP cannot read the EFS home; only a destroy task of this very run proves it"
}

// ProveHomeGone — ecs-ec2: the keep-list (.config, where the credential store lives) is on
// EFS, so the EBS volume being gone says nothing about it. The proof is the base adapter's.
func (e *ecsEC2Runtime) ProveHomeGone(ctx context.Context) (HomeVerdict, string) {
	return e.base.ProveHomeGone(ctx)
}

// ProveHomeGone — kubernetes: Destroy deletes the StatefulSet last, and only when its
// inventory shows every claim and volume gone, so that delete is the proof. A volume's name
// is generated by the provisioner and cannot be listed back, so a StatefulSet that is merely
// absent (inventory lost with it) proves nothing about the disks.
func (k *kubeRuntime) ProveHomeGone(ctx context.Context) (HomeVerdict, string) {
	if k.homeDestroyed {
		return HomeGone, "destroy confirmed every claim and volume gone"
	}
	s, err := k.getStatefulSet(ctx)
	switch {
	case err != nil:
		return HomeUnknown, "the StatefulSet cannot be read: " + err.Error()
	case s != nil:
		return HomePresent, "the StatefulSet exists"
	}
	return HomeUnknown, "no StatefulSet, but the volumes cannot be listed back; only a destroy of this very run proves them gone"
}
